#!/usr/bin/env python3
"""Generate or check src/ud3tn/fields.rs from uD3TN's aap2.proto.

    gen_fields.py PATH/TO/aap2.proto            # print fields.rs to stdout
    gen_fields.py PATH/TO/aap2.proto --check    # compare with src/ud3tn/fields.rs

The Rust client hand-encodes protobuf, so its field numbers must match the
agent's .proto exactly. This reads the .proto (a plain proto3 parser, enough
for aap2.proto: messages, nested messages, oneofs, enums) and emits the
constants the client uses. --check exits 1 and prints every mismatch.
"""

import re
import sys
from pathlib import Path

# (rust constant, message, field)
FIELDS = [
    ("AAP_MESSAGE_WELCOME", "AAPMessage", "welcome"),
    ("AAP_MESSAGE_CONFIG", "AAPMessage", "config"),
    ("AAP_MESSAGE_ADU", "AAPMessage", "adu"),
    ("AAP_MESSAGE_KEEPALIVE", "AAPMessage", "keepalive"),
    ("AAP_RESPONSE_RESPONSE_STATUS", "AAPResponse", "response_status"),
    ("WELCOME_NODE_ID", "Welcome", "node_id"),
    ("CONNECTION_CONFIG_IS_SUBSCRIBER", "ConnectionConfig", "is_subscriber"),
    ("CONNECTION_CONFIG_AUTH_TYPE", "ConnectionConfig", "auth_type"),
    ("CONNECTION_CONFIG_SECRET", "ConnectionConfig", "secret"),
    ("CONNECTION_CONFIG_ENDPOINT_ID", "ConnectionConfig", "endpoint_id"),
    ("CONNECTION_CONFIG_KEEPALIVE_SECONDS", "ConnectionConfig", "keepalive_seconds"),
    ("BUNDLE_ADU_SRC_EID", "BundleADU", "src_eid"),
    ("BUNDLE_ADU_DST_EID", "BundleADU", "dst_eid"),
    ("BUNDLE_ADU_CREATION_TIMESTAMP_MS", "BundleADU", "creation_timestamp_ms"),
    ("BUNDLE_ADU_SEQUENCE_NUMBER", "BundleADU", "sequence_number"),
    ("BUNDLE_ADU_PAYLOAD_LENGTH", "BundleADU", "payload_length"),
    ("BUNDLE_ADU_ADU_FLAGS", "BundleADU", "adu_flags"),
]

# (rust constant, enum, value name)
ENUMS = [
    ("RESPONSE_STATUS_SUCCESS", "ResponseStatus", "RESPONSE_STATUS_SUCCESS"),
    ("RESPONSE_STATUS_ACK", "ResponseStatus", "RESPONSE_STATUS_ACK"),
    ("AUTH_TYPE_DEFAULT", "AuthType", "AUTH_TYPE_DEFAULT"),
    ("BUNDLE_ADU_NORMAL", "BundleADUFlags", "BUNDLE_ADU_NORMAL"),
]

# Expected scalar types, so a renamed-but-retyped field is caught too.
TYPES = {
    ("Welcome", "node_id"): "string",
    ("AAPResponse", "response_status"): "ResponseStatus",
    ("ConnectionConfig", "is_subscriber"): "bool",
    ("ConnectionConfig", "auth_type"): "AuthType",
    ("ConnectionConfig", "secret"): "string",
    ("ConnectionConfig", "endpoint_id"): "string",
    ("ConnectionConfig", "keepalive_seconds"): "uint32",
    ("BundleADU", "src_eid"): "string",
    ("BundleADU", "dst_eid"): "string",
    ("BundleADU", "creation_timestamp_ms"): "uint64",
    ("BundleADU", "sequence_number"): "uint64",
    ("BundleADU", "payload_length"): "uint64",
}

FIELD_RE = re.compile(
    r"^(?:optional\s+|repeated\s+)?([\w.]+)\s+(\w+)\s*=\s*(\d+)\s*(?:\[[^\]]*\])?\s*;"
)
ENUMVAL_RE = re.compile(r"^(\w+)\s*=\s*(-?\d+)\s*(?:\[[^\]]*\])?\s*;")
OPEN_RE = re.compile(r"^(message|enum|oneof)\s+(\w+)\s*\{")


def parse(text):
    """Return ({(message, field): (type, number)}, {(enum, name): value})."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    # One statement per line: split after braces and semicolons.
    text = re.sub(r"([{};])", r"\1\n", text)
    fields, enums = {}, {}
    stack = []  # [(kind, name)]
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        m = OPEN_RE.match(line)
        if m:
            stack.append((m.group(1), m.group(2)))
            continue
        if line.startswith("}"):
            if stack:
                stack.pop()
            continue
        if not stack:
            continue
        kind, name = stack[-1]
        if kind == "enum":
            m = ENUMVAL_RE.match(line)
            if m:
                enums[(name, m.group(1))] = int(m.group(2))
            continue
        # A oneof's fields belong to the enclosing message.
        owner = next(n for k, n in reversed(stack) if k == "message")
        m = FIELD_RE.match(line)
        if m and not line.startswith(("option", "reserved")):
            fields[(owner, m.group(2))] = (m.group(1), int(m.group(3)))
    return fields, enums


def generate(fields, enums):
    errors, out = [], []
    out.append("// AAP 2.0 protobuf field numbers and enum values used by `ud3tn`.")
    out.append("//")
    out.append("// GENERATED by integrations/ud3tn/gen_fields.py from uD3TN's")
    out.append("// components/aap2/aap2.proto. Do not edit by hand.")
    out.append("//")
    out.append("// proto-source: checked")
    out.append("")
    for const, msg, field in FIELDS:
        got = fields.get((msg, field))
        if got is None:
            errors.append(f"{msg}.{field}: not in the .proto")
            continue
        typ, num = got
        want = TYPES.get((msg, field))
        if want and typ.split(".")[-1] != want:
            errors.append(f"{msg}.{field}: type {typ}, client expects {want}")
        out.append(f"pub const {const}: u32 = {num};")
    out.append("")
    for const, enum, name in ENUMS:
        val = enums.get((enum, name))
        if val is None:
            errors.append(f"{enum}.{name}: not in the .proto")
            continue
        out.append(f"pub const {const}: u64 = {val};")
    return "\n".join(out) + "\n", errors


def constants(rust):
    return dict(re.findall(r"pub const (\w+): u\d+ = (\d+);", rust))


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    proto = Path(sys.argv[1]).read_text()
    rust, errors = generate(*parse(proto))
    for e in errors:
        print("error:", e, file=sys.stderr)
    if "--check" in sys.argv:
        here = Path(__file__).resolve().parents[2] / "src" / "ud3tn" / "fields.rs"
        have, want = constants(here.read_text()), constants(rust)
        bad = [
            f"{k}: fields.rs has {have.get(k)}, aap2.proto says {v}"
            for k, v in want.items()
            if have.get(k) != v
        ]
        for b in bad:
            print("mismatch:", b)
        if bad or errors:
            print(f"\nregenerate: {sys.argv[0]} {sys.argv[1]} > {here}")
            sys.exit(1)
        print(f"fields.rs agrees with {sys.argv[1]} ({len(want)} constants)")
        return
    if errors:
        sys.exit(1)
    sys.stdout.write(rust)


if __name__ == "__main__":
    main()
